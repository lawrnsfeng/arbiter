def _unit(path: str, lang: str, added: list[str], removed=()):
    f = {"path": path, "hunks": [{"added": [[i + 1, t] for i, t in enumerate(added)], "removed": list(removed)}]}
    return {"files": [{"path": path, "lang": lang, "hunks": [0]}]}, {path: f}


