def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), "-c", "commit.gpgsign=false", "-c", "user.name=t", "-c", "user.email=t@t",
                    *args], check=True, capture_output=True)


def mkrepo(tmp: Path, base: dict[str, str], head: dict[str, str]) -> Path:
    repo = tmp / "repo"
    repo.mkdir()
    git(repo, "init", "-q", "-b", "master")
    for files, msg in ((base, "base"), (head, "head")):
        for path, text in files.items():
            p = repo / path
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        git(repo, "add", "-A")
        git(repo, "commit", "-q", "--allow-empty", "-m", msg)
    return repo


def ffile(path: str, churns: list[int]) -> dict:
    hunks, start = [], 1
    for c in churns:
        hunks.append({"churn": c, "new_start": start, "new_count": c, "added": [[start + i, "x"] for i in range(c)],
                      "removed": []})
        start += c + 10
    return {"path": path, "lang": "python", "churn": sum(churns), "hunks": hunks}


