def _report_run(tmp_path: Path, severity: str) -> Path:
    run = tmp_path / "run"
    run.mkdir()
    plan = {"repo": str(tmp_path), "base": "a" * 40, "head": "b" * 40, "effort": "standard"}
    f = {
        "id": "f001",
        "axis": "logic",
        "group": "functional",
        "severity": severity,
        "file": "a.py",
        "line": 3,
        "claim": "c",
        "placement": "main",
        "proof": {"rung": "E4", "result": "confirmed", "before": {"cmd": "pytest", "exit_code": 1}},
    }
    (run / "plan.json").write_text(json.dumps(plan))
    (run / "final.json").write_text(json.dumps([f]))
    return run


