def cand(**kw):
    c = {"axis": "logic", "severity": "block", "file": "a.py", "line": 10, "claim": "wrong", "trigger": "x=1",
         "evidence_lines": ["a.py:10"], "proof_plan": {"rung": "E4", "idea": "test"}, "agent": "A1a", "pass": 0,
         "unit": "u01"}
    c.update(kw)
    return c


