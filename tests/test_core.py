def test_lockfile_and_generated_excluded_but_listed(tmp_path):
    repo = mkrepo(tmp_path, {"a.py": "x = 1\n"}, {
        "a.py": "x = 2\n", "uv.lock": "lock\n", "gen.go": "// Code generated by x. DO NOT EDIT.\npackage p\n"})
    d = diff.collect(repo, diff.resolve_base(repo, "HEAD~1"))
    ex = {f["path"]: f["excluded"] for f in d["files"]}
    assert ex == {"a.py": None, "uv.lock": "lockfile", "gen.go": "generated"}
    us = units.build([f for f in d["files"] if not f["excluded"]], set())
    assert [x["path"] for u in us for x in u["files"]] == ["a.py"]


